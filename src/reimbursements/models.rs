//! Persistence models for the `reimbursements` module.
//!
//! The shapes mirror `docs/database/schema.md` §11.1 (`expense_claims`) and
//! §11.2 (`expense_items`) column for column, so a row read by a repository
//! statement decodes without a projection that renames anything.
//!
//! # Money
//!
//! Every money column is `NUMERIC(19,4)`. SQLx cannot decode `NUMERIC` with
//! this crate's feature set, and `ADR-0007` forbids a decimal crate, so the
//! repository selects the column as `total_amount::text` / `amount::text` and
//! the value is carried here as it arrives. `NUMERIC(19,4)::text` renders
//! exactly four decimal places, which is the published wire form.
//!
//! The type is a plain `String` on purpose. A `Money` newtype would suggest
//! arithmetic that does not exist: nothing in Rust adds, rounds, parses or
//! compares money. The total is computed by `SUM(amount)` in SQL, in the same
//! transaction as the item write, and an amount is bound back as a string cast
//! to `numeric`. There is no `f32` or `f64` in this path.

use chrono::{DateTime, NaiveDate, Utc};
use serde::{Deserialize, Serialize};
use sqlx::FromRow;
use utoipa::ToSchema;
use uuid::Uuid;

/// The lifecycle state of an expense claim.
///
/// The set is constrained by the database (`expense_claim_status` enum type)
/// and by the application, so an out-of-contract value can never be persisted.
/// The five arms and the timestamp each one requires are the ones
/// `expense_claims_lifecycle_timestamps_chk` enforces.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, sqlx::Type, ToSchema)]
#[serde(rename_all = "snake_case")]
#[sqlx(type_name = "expense_claim_status", rename_all = "snake_case")]
pub enum ClaimStatus {
    /// Recorded, not yet sent for approval.
    Draft,
    /// Sent for approval; carries `submitted_at`.
    Submitted,
    /// Approved; carries `submitted_at` and `decided_at`.
    Approved,
    /// Rejected; carries `submitted_at` and `decided_at`.
    Rejected,
    /// Reimbursed; carries `submitted_at`, `decided_at` and `paid_at`.
    Paid,
}

/// An expense claim row.
///
/// `total_amount` is the `text` form of a `NUMERIC(19,4)`; see the module
/// documentation. `currency` is the `CHAR(3)` column; a three-character code
/// carries no padding, so the value reads back exactly as it was written.
#[derive(Debug, Clone, FromRow)]
pub struct ExpenseClaim {
    /// Primary key, generated by the application.
    pub id: Uuid,
    /// The owner. Every statement filters on this column.
    pub user_id: Uuid,
    /// Claim title, 1 to 200 characters.
    pub title: String,
    /// Optional at the API, `''` in the database, exactly like `notes.content`.
    pub description: String,
    /// ISO 4217 currency code, three upper-case letters.
    pub currency: String,
    /// The sum of the claim's items, as `NUMERIC(19,4)::text`.
    pub total_amount: String,
    /// The lifecycle state.
    pub status: ClaimStatus,
    /// The optional project link, cleared when the project is deleted.
    pub project_id: Option<Uuid>,
    /// Set exactly when the status requires it.
    pub submitted_at: Option<DateTime<Utc>>,
    /// The approve or reject instant.
    pub decided_at: Option<DateTime<Utc>>,
    /// The payment instant.
    pub paid_at: Option<DateTime<Utc>>,
    /// Creation instant.
    pub created_at: DateTime<Utc>,
    /// Last modification instant.
    pub updated_at: DateTime<Utc>,
}

/// A line item of an expense claim.
///
/// An item has no currency of its own: it is denominated in its claim's
/// currency. `amount` is the `text` form of a `NUMERIC(19,4)`; see the module
/// documentation.
#[derive(Debug, Clone, FromRow)]
pub struct ExpenseItem {
    /// Primary key, generated by the application.
    pub id: Uuid,
    /// The owner. The composite key to `expense_claims (id, user_id)` makes
    /// this equal to the claim's owner by construction.
    pub user_id: Uuid,
    /// The claim this item belongs to.
    pub claim_id: Uuid,
    /// Line description, 1 to 500 characters.
    pub description: String,
    /// The amount, as `NUMERIC(19,4)::text`.
    pub amount: String,
    /// A calendar date, not an instant.
    pub incurred_on: NaiveDate,
    /// Optional lower-case category token.
    pub category: Option<String>,
    /// Optional client-supplied `http` or `https` reference.
    pub receipt_url: Option<String>,
    /// Creation instant.
    pub created_at: DateTime<Utc>,
    /// Last modification instant.
    pub updated_at: DateTime<Utc>,
}
