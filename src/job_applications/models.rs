//! Persistence models for the `job_applications` module.
//!
//! The shapes mirror `docs/database/schema.md` §11.3 (`companies`), §11.4
//! (`job_applications`) and §11.5 (`application_events`) column for column, so
//! a row read by a repository statement decodes without a projection that
//! renames anything.
//!
//! Every row carries `user_id`, not only its parent. That is what lets the
//! ownership predicate of every statement be a column of the table it reads
//! (`ADR-0005`); the composite foreign keys keep the child's owner equal to the
//! parent's, so the column cannot disagree with the join.
//!
//! # Money
//!
//! `salary_min` and `salary_max` are `NUMERIC(19,4)`. SQLx cannot decode
//! `NUMERIC` with this crate's feature set, and `ADR-0007` forbids a decimal
//! crate, so the repository selects the column as `salary_min::text` /
//! `salary_max::text` and the value is carried here as it arrives.
//! `NUMERIC(19,4)::text` renders exactly four decimal places, which is the
//! published wire form.
//!
//! The type is a plain `String` on purpose, for the same reason as the claim
//! amounts: nothing in Rust adds, rounds, parses or compares salary bounds. The
//! ordering rule (`min <= max`) is a database `CHECK`, and a bound is bound
//! back as a string cast to `numeric`. There is no `f32` or `f64` in this path.

use chrono::{DateTime, NaiveDate, Utc};
use serde::{Deserialize, Serialize};
use sqlx::FromRow;
use utoipa::ToSchema;
use uuid::Uuid;

/// The stage of a job application.
///
/// The seven values are the database's `job_application_status` type, so an
/// unknown stage is unrepresentable. The type does **not** express the allowed
/// transitions: a `CHECK` sees one row and cannot see the previous status, so
/// `wishlist → interview` can only be refused by the service (`JOB-R04`). The
/// enum is the half the database can own.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, sqlx::Type, ToSchema)]
#[serde(rename_all = "snake_case")]
#[sqlx(type_name = "job_application_status", rename_all = "snake_case")]
pub enum ApplicationStatus {
    /// Found, not yet applied to.
    Wishlist,
    /// An application has been sent.
    Applied,
    /// The company is screening the candidate.
    Screening,
    /// At least one interview has happened or is scheduled.
    Interview,
    /// An offer has been made.
    Offer,
    /// The company declined.
    Rejected,
    /// The owner withdrew.
    Withdrawn,
}

/// The kind of one entry in an application's timeline.
///
/// A separate type from [`ApplicationStatus`] on purpose: the two vocabularies
/// share two words but are not the same list, and one type for both would let
/// an application be stored as `call`.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, sqlx::Type, ToSchema)]
#[serde(rename_all = "snake_case")]
#[sqlx(type_name = "application_event_kind", rename_all = "snake_case")]
pub enum ApplicationEventKind {
    /// A free-form note the owner wrote.
    Note,
    /// An email exchange.
    Email,
    /// A telephone or video call.
    Call,
    /// An interview.
    Interview,
    /// An offer was discussed or extended.
    Offer,
    /// A rejection arrived.
    Rejection,
}

/// An employer row.
///
/// `name` is stored with the casing the owner typed and compared folded, so
/// `companies_user_id_lower_name_unique_idx` is what makes it unique per owner;
/// the application lower-cases nothing here, unlike a user's email address.
#[derive(Debug, Clone, FromRow)]
pub struct Company {
    /// Primary key, generated by the application.
    pub id: Uuid,
    /// The owner. Every statement filters on this column.
    pub user_id: Uuid,
    /// Trimmed, 1 to 200 characters; unique per owner case-insensitively.
    pub name: String,
    /// Optional `http` or `https` reference, at most 2 048 characters.
    pub website: Option<String>,
    /// Optional free text, at most 5 000 characters; `''` in the database.
    pub notes: String,
    /// Creation instant.
    pub created_at: DateTime<Utc>,
    /// Last modification instant.
    pub updated_at: DateTime<Utc>,
}

/// A job application row.
///
/// The company is reached through the composite key
/// `(company_id, user_id) → companies (id, user_id)`, so `company_id` always
/// names a company of the same owner.
#[derive(Debug, Clone, FromRow)]
pub struct JobApplication {
    /// Primary key, generated by the application.
    pub id: Uuid,
    /// The owner. Every statement filters on this column.
    pub user_id: Uuid,
    /// The employer; its owner equals this row's owner by construction.
    pub company_id: Uuid,
    /// Trimmed role title, 1 to 200 characters.
    pub role_title: String,
    /// Where the lead came from; a label, not a controlled value.
    pub source: Option<String>,
    /// The seven-stage state.
    pub status: ApplicationStatus,
    /// The calendar day the application was sent; `NULL` on a `wishlist` row.
    pub applied_on: Option<NaiveDate>,
    /// Optional lower bound, as `NUMERIC(19,4)::text`; see the module docs.
    pub salary_min: Option<String>,
    /// Optional upper bound, as `NUMERIC(19,4)::text`; see the module docs.
    pub salary_max: Option<String>,
    /// ISO 4217 code, required whenever either bound is present.
    pub salary_currency: Option<String>,
    /// Optional posting reference, at most 2 048 characters.
    pub job_url: Option<String>,
    /// Optional free text, at most 10 000 characters; `''` in the database.
    pub description: String,
    /// The optional next-action task, cleared when the task is deleted.
    ///
    /// Ownership cannot be enforced by a composite key here: `tasks` has no
    /// `user_id` (§6 of `schema.md`). The service checks
    /// `tasks → projects → user_id` before writing (`JOB-R07`).
    pub next_action_task_id: Option<Uuid>,
    /// Creation instant.
    pub created_at: DateTime<Utc>,
    /// Last modification instant.
    pub updated_at: DateTime<Utc>,
}

/// One dated entry in an application's timeline.
///
/// There is deliberately no `updated_at`: a timeline entry records what the
/// owner says happened, and its fields are corrected in place (decision
/// `A-D1-1`). `created_at` is the row's creation instant; `occurred_at` is the
/// event's own time and may be in the future, because an interview can be
/// scheduled.
#[derive(Debug, Clone, FromRow)]
pub struct ApplicationEvent {
    /// Primary key, generated by the application.
    pub id: Uuid,
    /// The owner; equal to the application's owner by construction.
    pub user_id: Uuid,
    /// The application this event belongs to.
    pub application_id: Uuid,
    /// What kind of entry this is.
    pub kind: ApplicationEventKind,
    /// The instant the event belongs at on the timeline.
    pub occurred_at: DateTime<Utc>,
    /// Trimmed summary, 1 to 200 characters.
    pub summary: String,
    /// Optional detail, at most 10 000 characters; `''` in the database.
    pub details: String,
    /// The row's creation instant, distinct from `occurred_at`.
    pub created_at: DateTime<Utc>,
}
