//! Persistence models for the `api_keys` module.
//!
//! The shapes mirror `api_keys` in `migrations/0007_api_keys.sql` column for
//! column, with one deliberate omission.
//!
//! # The hash is not on the row type
//!
//! [`ApiKey`] has no `key_hash` field. The column exists, and exactly one
//! statement reads it — the one that resolves a presented credential, which
//! binds a hash and returns a [`KeyIdentity`]. Everything that builds a
//! response is built from [`ApiKey`], so a response cannot carry the hash even
//! if a later change experimented with adding it: the field is not there to
//! select.
//!
//! The plaintext secret is never stored at all, so it has no model: it exists
//! as a `String` inside [`crate::api_keys::secret::GeneratedKey`] and in the
//! body of the create response, and nowhere else.

use chrono::{DateTime, Utc};
use sqlx::FromRow;
use uuid::Uuid;

/// An API-key row, as every response type sees it.
///
/// `user_id` is the owner and is used as the ownership predicate of every
/// statement; it never reaches the wire, exactly as `ClaimResponse` drops its
/// own.
#[derive(Debug, Clone, FromRow)]
pub struct ApiKey {
    /// Primary key, generated by the application.
    pub id: Uuid,
    /// The owner. Every statement filters on this column.
    pub user_id: Uuid,
    /// Operator-supplied label, 1 to 100 characters.
    pub name: String,
    /// `atom_` plus eight hex characters. Safe to display; the rest is absent.
    pub prefix: String,
    /// The last time the key authenticated a request, at most hourly.
    pub last_used_at: Option<DateTime<Utc>>,
    /// Creation instant.
    pub created_at: DateTime<Utc>,
    /// The revocation instant, or `None` while the key is live.
    pub revoked_at: Option<DateTime<Utc>>,
}

/// The account a presented secret belongs to.
///
/// This is the **only** shape that crosses from the credential to the caller.
/// It is read by one statement — the join from `api_keys` to `users` on the
/// bound hash — and it carries exactly the facts a request needs: whether the
/// key is live, whether the account may still act, and when the key was last
/// used.
///
/// # Two states, two answers
///
/// A revoked key and an inactive account are **different** answers, so they are
/// kept as different facts here and no method of this type collapses them:
///
/// * the **key** is not accepted → `401`, because the credential is the problem
///   and issuing another one is the remedy;
/// * the **account** may not authenticate → `403`, because the credential is
///   fine and the account is not. `AuthService::authenticate_bearer` answers
///   `403 messages.auth.account_disabled` for a JWT of the same account, and a
///   second credential type must not contradict it (amendment `A-C-K1-1`).
///
/// The service makes that decision ([`crate::api_keys::service::identity_refusal`],
/// which is the single definition of it); this type only states what is true.
#[derive(Debug, Clone, FromRow)]
pub struct KeyIdentity {
    /// The key that was presented, so its usage stamp can be updated.
    pub key_id: Uuid,
    /// The account the key acts for.
    pub user_id: Uuid,
    /// The account's address, which is the `email` on [`crate::api::middleware::AuthUser`].
    pub email: String,
    /// Whether the account is still allowed to authenticate.
    pub is_active: bool,
    /// The revocation instant, or `None` while the key is live.
    pub revoked_at: Option<DateTime<Utc>>,
    /// The last authenticated use, or `None` if the key has never been used.
    ///
    /// Read so that [`Self::needs_usage_stamp`] can skip a write the database
    /// would refuse anyway; it is not a state and nothing decides on it.
    pub last_used_at: Option<DateTime<Utc>>,
}

/// How long a `last_used_at` stamp stays fresh, in hours.
///
/// The **enforced** copy of this number is the predicate inside
/// `TOUCH_LAST_USED` in [`crate::api_keys::repository`]:
/// `last_used_at < NOW() - INTERVAL '1 hour'`. The database decides whether the
/// write happens, so two concurrent requests cannot both stamp. This constant
/// mirrors it for the pre-check in [`KeyIdentity::needs_usage_stamp`], which
/// only saves a round trip: a read that disagrees with the statement cannot
/// produce a second write inside the window, because the statement re-checks
/// the same condition on the committed row.
pub const USAGE_STAMP_INTERVAL_HOURS: i64 = 1;

impl KeyIdentity {
    /// Whether the next authenticated use has to be recorded, given the clock.
    ///
    /// `true` when the key has never been used, or when the stored stamp is at
    /// least [`USAGE_STAMP_INTERVAL_HOURS`] old. The caller uses it to skip a
    /// statement; the statement is what actually enforces the throttle.
    pub fn needs_usage_stamp(&self, now: DateTime<Utc>) -> bool {
        match self.last_used_at {
            None => true,
            // Strictly greater, which is the mirror of the statement's strict
            // `<`: `last < NOW() - 1 hour` is `now - last > 1 hour`. At exactly
            // the bound neither writes.
            Some(last) => {
                now.signed_duration_since(last)
                    > chrono::Duration::hours(USAGE_STAMP_INTERVAL_HOURS)
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn identity(last_used_at: Option<DateTime<Utc>>) -> KeyIdentity {
        KeyIdentity {
            key_id: Uuid::nil(),
            user_id: Uuid::nil(),
            email: "owner@atom.local".to_string(),
            is_active: true,
            revoked_at: None,
            last_used_at,
        }
    }

    #[test]
    fn a_key_that_has_never_been_used_needs_a_stamp() {
        assert!(identity(None).needs_usage_stamp(Utc::now()));
    }

    #[test]
    fn a_stamp_inside_the_hour_is_fresh_and_is_not_rewritten() {
        let now = Utc::now();

        // Just written: the hot-key case, which must cost no write at all.
        assert!(!identity(Some(now)).needs_usage_stamp(now));
        // Still inside the window.
        assert!(!identity(Some(now - chrono::Duration::minutes(59))).needs_usage_stamp(now));
    }

    #[test]
    fn a_stamp_at_or_past_the_hour_needs_a_new_one() {
        let now = Utc::now();

        // Exactly at the bound: the statement's strict `<` declines and so does
        // the pre-check, so the two agree on the boundary rather than one
        // costing a round trip the other refuses.
        assert!(!identity(Some(now - chrono::Duration::hours(1))).needs_usage_stamp(now));
        assert!(
            identity(Some(
                now - chrono::Duration::hours(1) - chrono::Duration::seconds(1)
            ))
            .needs_usage_stamp(now)
        );
        assert!(identity(Some(now - chrono::Duration::hours(2))).needs_usage_stamp(now));
    }
}
